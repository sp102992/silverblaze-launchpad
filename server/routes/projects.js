// Fetch a project's structure + every section's current data, for the manager dashboard.
router.get('/:projectName', async (req, res) => {
  const projectName = req.params.projectName;
  const project = projectStore.getProject(projectName);
  if (!project) return res.status(404).json({ error: 'Project not found. Retrieve or create it first.' });
  if (!canAccessProject(req.session, project)) {
    return res.status(403).json({ error: `You don't have access to "${project.projectName}".` });
  }
  try {
    const sections = {};
    for (const key of SECTION_KEYS) {
      const sheetId = project.sheets[key];
      // Idempotent — makes sure any manager-created custom field for this
      // section already has a column on THIS project's sheet, including
      // projects created before the field existed.
      await customFields.ensureColumnsForSection(smartsheet, sheetId, key);
      // Same idempotent backfill, but for this section's own hardcoded
      // fields — covers projects created before a secret field switched
      // from a "Provided" checkbox to storing its real value.
      await smartsheet.ensureSectionColumns(sheetId, key);
      const rowTitleCells = await smartsheet.getRowDataByClient(sheetId, projectName);
      sections[key] = {
        found: !!rowTitleCells,
        status: rowTitleCells ? rowTitleCells['Status'] || 'pending' : 'pending',
        data: rowTitleCells ? fromCells(key, rowTitleCells) : {},
      };
    }
    res.json({ project, sections, hostingType: project.hostingType || null });
  } catch (e) {
    console.error(e);
    res.status(500).json({ error: e.message });
  }
});

// Save one section's form data for a project (used by the manager dashboard).
router.post('/:projectName/sections/:sectionKey', async (req, res) => {
  const projectName = req.params.projectName;
  const sectionKey = req.params.sectionKey;
  if (!SECTIONS[sectionKey]) return res.status(400).json({ error: 'Unknown section: ' + sectionKey });
  const project = projectStore.getProject(projectName);
  if (!project) return res.status(404).json({ error: 'Project not found. Retrieve or create it first.' });
  if (!canAccessProject(req.session, project)) return res.status(403).json({ error: `You don't have access to "${project.projectName}".` });
  try {
    await customFields.ensureColumnsForSection(smartsheet, project.sheets[sectionKey], sectionKey);
    await smartsheet.ensureSectionColumns(project.sheets[sectionKey], sectionKey);
    const cells = toCells(sectionKey, req.body.formData || {});
    cells['Status'] = req.body.status || 'complete';
    cells['Submitted By'] = req.session.displayName || req.session.username || 'Manager';
    cells['Submitted At'] = new Date().toISOString();
    await smartsheet.upsertRow(project.sheets[sectionKey], projectName, cells);
    res.json({ ok: true });
  } catch (e) {
    console.error(e);
    res.status(500).json({ error: e.message });
  }
});

// ── HOSTING TYPE ────────────────────────────────────────────────────────
// The very first question asked after opening a project: is the environment
// Silverblaze-Azure-hosted or Client/BU-hosted? This single value gates
// Ansible Inventory (Client/BU only) and the vendor-IP-whitelisting fields
// (Silverblaze Azure only) everywhere else in the app — kept as one field on
// the project record (server/projectStore.js already merges arbitrary new
// keys with no changes needed there) rather than duplicated per-section.
router.get('/:projectName/hosting', async (req, res) => {
  const projectName = req.params.projectName;
  const project = projectStore.getProject(projectName);
  if (!project) return res.status(404).json({ error: 'Project not found. Retrieve or create it first.' });
  if (!canAccessProject(req.session, project)) return res.status(403).json({ error: `You don't have access to "${project.projectName}".` });
  res.json({ hostingType: project.hostingType || null, options: Object.values(HOSTING_TYPES) });
});

router.post('/:projectName/hosting', async (req, res) => {
  const projectName = req.params.projectName;
  const { hostingType } = req.body || {};
  if (!Object.values(HOSTING_TYPES).includes(hostingType)) {
    return res.status(400).json({ error: 'hostingType must be one of: ' + Object.values(HOSTING_TYPES).join(', ') });
  }
  const project = projectStore.getProject(projectName);
  if (!project) return res.status(404).json({ error: 'Project not found. Retrieve or create it first.' });
  if (!canAccessProject(req.session, project)) return res.status(403).json({ error: `You don't have access to "${project.projectName}".` });
  const record = projectStore.saveProject(projectName, { hostingType });
  res.json({ ok: true, hostingType: record.hostingType });
});

// Generate one shareable link per section. Each link is a signed token that
// only unlocks that single section for that single project — no Smartsheet
// credentials or IDs are ever exposed in the URL.
router.post('/:projectName/share-links', (req, res) => {
  const projectName = req.params.projectName;
  const project = projectStore.getProject(projectName);
  if (!project) return res.status(404).json({ error: 'Project not found. Retrieve or create it first.' });
  if (!canAccessProject(req.session, project)) return res.status(403).json({ error: `You don't have access to "${project.projectName}".` });
  const links = shareableSectionMetaList.map(({ key, label }) => {
    const token = createLinkToken({ projectName, sectionKey: key });
    return {
      sectionKey: key,
      label,
      owner: SECTIONS[key].owner,
      url: `${config.appBaseUrl}/customer.html?token=${token}`,
    };
  });
  res.json({ links });
});

// Email one section's share link directly to a recipient, and remember who
// it went to + when — this is the only place a section's shareLinks entry
// gets created, since it's the only place we actually have a recipient
// address to remind later (see server/reminders.js). projectStore.saveProject
// shallow-merges only at the top level, so we read the existing map first
// and merge the single section in ourselves before saving.
router.post('/:projectName/share-links/:sectionKey/send-email', async (req, res) => {
  const projectName = req.params.projectName;
  const sectionKey = req.params.sectionKey;
  const { to } = req.body || {};
  if (!SECTIONS[sectionKey]) return res.status(400).json({ error: 'Unknown section: ' + sectionKey });
  if (!to || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(to)) {
    return res.status(400).json({ error: 'A valid recipient email is required.' });
  }
  const project = projectStore.getProject(projectName);
  if (!project) return res.status(404).json({ error: 'Project not found. Retrieve or create it first.' });
  if (!canAccessProject(req.session, project)) return res.status(403).json({ error: `You don't have access to "${project.projectName}".` });

  const label = SECTIONS[sectionKey].label;
  const token = createLinkToken({ projectName, sectionKey });
  const url = `${config.appBaseUrl}/customer.html?token=${token}`;

  const result = await sendShareLinkEmail(to, { projectName, sectionKey, label, url });

  const shareLinks = { ...(project.shareLinks || {}) };
  shareLinks[sectionKey] = {
    token,
    url,
    recipientEmail: to,
    issuedAt: Date.now(),
    lastRemindedAt: null,
  };
  projectStore.saveProject(projectName, { shareLinks });

  if (!result.ok && result.reason === 'not_configured') {
    return res.json({ ok: true, delivered: false, url, note: 'SMTP is not configured on this server — the link was generated but no email was sent. Copy it manually below.' });
  }
  if (!result.ok) {
    return res.status(502).json({ error: 'Link was generated but the email failed to send: ' + result.reason, url });
  }
  res.json({ ok: true, delivered: true, url });
});

// Pull every section's live Smartsheet data and build the .properties text,
// using configKeyMap.js to translate internal field ids into the real
// property names your own utility portal expects.
async function loadAllSectionData(project, projectName) {
  const sections = {};
  for (const key of SECTION_KEYS) {
    const sheetId = project.sheets[key];
    const rowTitleCells = await smartsheet.getRowDataByClient(sheetId, projectName);
    sections[key] = {
      found: !!rowTitleCells,
      status: rowTitleCells ? rowTitleCells['Status'] || 'pending' : 'pending',
      data: rowTitleCells ? fromCells(key, rowTitleCells) : {},
    };
  }
  return sections;
}

router.post('/:projectName/config/generate', async (req, res) => {
  const projectName = req.params.projectName;
  const project = projectStore.getProject(projectName);
  if (!project) return res.status(404).json({ error: 'Project not found. Retrieve or create it first.' });
  if (!canAccessProject(req.session, project)) return res.status(403).json({ error: `You don't have access to "${project.projectName}".` });
  try {
    const sections = await loadAllSectionData(project, projectName);
    const configText = buildConfigText(projectName, sections);
    res.json({ configText, filename: `${projectName.replace(/\s+/g, '-').toLowerCase()}-config.properties` });
  } catch (e) {
    console.error(e);
    res.status(500).json({ error: e.message });
  }
});

// Same as generate, but also writes the resulting text into a dedicated
// "Final Configuration" sheet in the project's Workspace, so it's saved
// alongside everything else in Smartsheet, not just downloaded once.
router.post('/:projectName/config/save', async (req, res) => {
  const projectName = req.params.projectName;
  const project = projectStore.getProject(projectName);
  if (!project) return res.status(404).json({ error: 'Project not found. Retrieve or create it first.' });
  if (!canAccessProject(req.session, project)) return res.status(403).json({ error: `You don't have access to "${project.projectName}".` });
  try {
    const sections = await loadAllSectionData(project, projectName);
    const configText = buildConfigText(projectName, sections);

    let configSheetId = project.configSheetId;
    if (!configSheetId) {
      const sheet = await smartsheet.ensureSheetInWorkspace(project.workspaceId, CONFIG_SHEET_NAME, CONFIG_SHEET_COLUMNS);
      configSheetId = sheet.id;
      projectStore.saveProject(projectName, { configSheetId });
    }

    await smartsheet.upsertRow(configSheetId, projectName, {
      'Config File': configText,
      'Generated By': req.session.displayName || req.session.username || 'Manager',
      'Generated At': new Date().toISOString(),
    });

    res.json({ ok: true, configText });
  } catch (e) {
    console.error(e);
    res.status(500).json({ error: e.message });
  }
});

