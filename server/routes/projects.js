const express = require('express');
const config = require('../config');
const smartsheet = require('../smartsheetClient');
const projectStore = require('../projectStore');
const { SECTION_KEYS, SECTIONS, HOSTING_TYPES, toCells, fromCells } = require('../sectionSchemas');
const { requireAuth } = require('../authMiddleware');
const { createLinkToken } = require('../linkTokens');
const { sendShareLinkEmail } = require('../email');
const { findClosestMatch, isExactMatch } = require('../similarity');
