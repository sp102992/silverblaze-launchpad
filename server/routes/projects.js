const { canAccessProject, visibleProjects } = require('../permissions');
const customFields = require('../customFields');

const router = express.Router();
router.use(requireAuth);

const sectionMetaList = SECTION_KEYS.map((key) => ({ key, label: SECTIONS[key].label }));
// Project Information for PM now gets a share link too, same as every other
// intake section (a PS team member can hand this specific link to the PM) —
// see the "additional changes" spec, item 3. Kept as its own list (rather
// than always equal to sectionMetaList) so a future section could still be
// excluded from sharing without re-touching every call site.
const shareableSectionMetaList = sectionMetaList;

const CONFIG_SHEET_NAME = 'Final Configuration';
const CONFIG_SHEET_COLUMNS = [
  { title: 'Client Name', type: 'TEXT_NUMBER', primary: true },
  { title: 'Config File', type: 'TEXT_NUMBER' },
  { title: 'Generated By', type: 'TEXT_NUMBER' },
  { title: 'Generated At', type: 'TEXT_NUMBER' },
];

// ── CREATE — only ever makes a new Workspace + Sheets ─────────────────────
// If an exact-name project already exists, this refuses (use Retrieve
// instead). If a similarly-named one exists (likely typo) and the caller
// hasn't confirmed, it asks first instead of silently creating a duplicate.
router.post('/create', async (req, res) => {
  const { projectName, confirm } = req.body;
  if (!projectName || !projectName.trim()) return res.status(400).json({ error: 'projectName is required' });
  const name = projectName.trim();

  const existing = projectStore.listProjects();
  const exactMatch = existing.find((p) => isExactMatch(p.projectName, name));
  if (exactMatch) {
    return res.status(409).json({
      error: `A project named "${exactMatch.projectName}" already exists. Use Retrieve Existing Project instead.`,
      exactMatch: exactMatch.projectName,
    });
  }

  if (!confirm) {
    // Non-managers only see typo suggestions among projects they can
    // already access — otherwise a "did you mean X" would leak the name of
    // a project they have no visibility into.
    const suggestible = visibleProjects(req.session, existing);
    const similar = findClosestMatch(name, suggestible.map((p) => p.projectName));
    if (similar) {
      return res.status(409).json({
        needsConfirm: true,
        similarTo: similar,
        error: `A similar project "${similar}" already exists. Did you mean to retrieve that one, or create "${name}" as a separate new project?`,
      });
    }
  }

  try {
    const structure = await smartsheet.ensureProjectStructure(name, sectionMetaList);
    const record = projectStore.saveProject(name, {
      workspaceId: structure.workspaceId,
      sheets: structure.sheets,
      // Whoever creates a project can always see it, regardless of role.
      createdBy: req.session.username,
    });
    res.json({ ok: true, project: record });
  } catch (e) {
    console.error(e);
    res.status(500).json({ error: e.message });
  }
});

// ── RETRIEVE — only ever finds, never creates ─────────────────────────────
router.post('/retrieve', async (req, res) => {
  const { projectName } = req.body;
  if (!projectName || !projectName.trim()) return res.status(400).json({ error: 'projectName is required' });
  const name = projectName.trim();

  const project = projectStore.getProject(name);
  if (!project) {
    const suggestible = visibleProjects(req.session, projectStore.listProjects());
    const similar = findClosestMatch(name, suggestible.map((p) => p.projectName));
    return res.status(404).json({
      error: similar
        ? `No existing project found for "${name}". Did you mean "${similar}"?`
        : `No existing project found for "${name}".`,
      suggestion: similar || null,
    });
  }
  if (!canAccessProject(req.session, project)) {
    return res.status(403).json({ error: `You don't have access to "${project.projectName}". Ask a manager to assign you to it.` });
  }
  res.json({ ok: true, project });
});

